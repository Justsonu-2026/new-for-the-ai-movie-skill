def main():
    for skill, cases in E.items():
        path = os.path.join(SKILLS, skill, "evals", "evals.json")
        os.makedirs(os.path.dirname(path), exist_ok=True)
        data = {"skill_name": skill, "evals": [
            {"id": i, "prompt": p, "expected_output": exp, "files": [], "expectations": ex}
            for i, (p, exp, ex) in enumerate(cases, 1)]}
        with open(path, "w", encoding="utf-8") as fh:
            json.dump(data, fh, indent=2, ensure_ascii=False)
            fh.write("\n")
    print(f"wrote evals for {len(E)} skills, {sum(len(c) for c in E.values())} cases")


if __name__ == "__main__":
    main()
