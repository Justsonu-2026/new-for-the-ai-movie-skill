#!/usr/bin/env python3
"""Turn a cut list CSV into a CMX3600 EDL and/or an ffmpeg rough-cut script.

Usage:
    python build_cut.py cutlist.csv --fps 24 [--title NAME] [--edl cut.edl] [--ffmpeg assemble.sh]
                        [--resolution 1920x1080] [--start-tc 01:00:00:00] [--with-audio]

cutlist.csv columns (header required):
    event,shot,file,src_in,src_out,transition,notes
  - src_in / src_out: seconds (e.g. 0.5) or timecode HH:MM:SS:FF
  - transition: cut (default) | dissolve:<frames> | fade-in | fade-out (non-cuts are written as EDL comments)
  - file paths are relative to the CSV's folder or absolute

Only the Python standard library is used. The ffmpeg script is written, not run.
"""
import argparse
import csv
import os
import shlex
import sys

REQUIRED_COLUMNS = ["event", "shot", "file", "src_in", "src_out"]


def to_frames(value, fps):
    value = str(value).strip()
    if value.count(":") == 3:
        h, m, s, f = (int(x) for x in value.split(":"))
        return ((h * 60 + m) * 60 + s) * fps + f
    return int(round(float(value) * fps))


def tc(frames, fps):
    f = frames % fps
    s = frames // fps
    return f"{s // 3600:02d}:{(s // 60) % 60:02d}:{s % 60:02d}:{f:02d}"


def load(path, fps):
    with open(path, newline="", encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    if not rows:
        sys.exit(f"ERROR: {path} has no rows")
    missing = [c for c in REQUIRED_COLUMNS if c not in rows[0]]
    if missing:
        sys.exit(f"ERROR: {path} is missing columns {missing}; expected {REQUIRED_COLUMNS + ['transition', 'notes']}")
    events = []
    for i, r in enumerate(rows, 2):
        try:
            a, b = to_frames(r["src_in"], fps), to_frames(r["src_out"], fps)
        except ValueError:
            sys.exit(f"ERROR: line {i}: src_in/src_out must be seconds or HH:MM:SS:FF")
        if b <= a:
            sys.exit(f"ERROR: line {i} ({r['shot']}): src_out must be after src_in")
        events.append({**r, "in": a, "out": b, "transition": (r.get("transition") or "cut").strip().lower()})
    return events


def write_edl(events, fps, title, start_tc, path, with_audio):
    rec = to_frames(start_tc, fps)
    channel = "AA/V" if with_audio else "V"
    lines = [f"TITLE: {title}", "FCM: NON-DROP FRAME", ""]
    for n, e in enumerate(events, 1):
        dur = e["out"] - e["in"]
        lines.append(f"{n:03d}  AX       {channel:<5} C        {tc(e['in'], fps)} {tc(e['out'], fps)} "
                     f"{tc(rec, fps)} {tc(rec + dur, fps)}")
        lines.append(f"* FROM CLIP NAME: {os.path.basename(e['file'])}")
        lines.append(f"* COMMENT: {e['shot']}" + (f" | {e['notes']}" if e.get("notes") else ""))
        if e["transition"] != "cut":
            lines.append(f"* TRANSITION REQUESTED: {e['transition']} (apply in the editor)")
        lines.append("")
        rec += dur
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    return rec - to_frames(start_tc, fps)


def write_ffmpeg(events, fps, resolution, base, path):
    w, h = resolution.lower().split("x")
    vf = (f"scale={w}:{h}:force_original_aspect_ratio=decrease,pad={w}:{h}:(ow-iw)/2:(oh-ih)/2,"
          f"fps={fps},format=yuv420p")
    out = ["#!/bin/sh", "# Rough cut assembly generated by build_cut.py. Review before running.",
           "set -e", 'mkdir -p rough_parts', ': > rough_parts/list.txt']
    for n, e in enumerate(events, 1):
        src = e["file"] if os.path.isabs(e["file"]) else os.path.join(base, e["file"])
        part = f"rough_parts/{n:03d}_{e['shot']}.mp4"
        ss, to = e["in"] / fps, e["out"] / fps
        out.append(f"ffmpeg -y -ss {ss:.3f} -to {to:.3f} -i {shlex.quote(src)} -vf {shlex.quote(vf)} "
                   f"-c:v libx264 -crf 18 -preset medium -c:a aac -ar 48000 -ac 2 {shlex.quote(part)}")
        out.append(f"echo \"file '{os.path.basename(part)}'\" >> rough_parts/list.txt")
    out.append("ffmpeg -y -f concat -safe 0 -i rough_parts/list.txt -c copy rough_cut.mp4")
    out.append('echo "Wrote rough_cut.mp4"')
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    os.chmod(path, 0o755)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cutlist")
    ap.add_argument("--fps", type=int, default=24)
    ap.add_argument("--title", default="ROUGH CUT")
    ap.add_argument("--edl")
    ap.add_argument("--ffmpeg")
    ap.add_argument("--resolution", default="1920x1080")
    ap.add_argument("--start-tc", default="01:00:00:00")
    ap.add_argument("--with-audio", action="store_true", help="EDL events carry audio (AA/V)")
    args = ap.parse_args()
    events = load(args.cutlist, args.fps)
    total = sum(e["out"] - e["in"] for e in events)
    if args.edl:
        write_edl(events, args.fps, args.title, args.start_tc, args.edl, args.with_audio)
        print(f"Wrote {args.edl}")
    if args.ffmpeg:
        write_ffmpeg(events, args.fps, args.resolution, os.path.dirname(os.path.abspath(args.cutlist)), args.ffmpeg)
        print(f"Wrote {args.ffmpeg}")
    print(f"{len(events)} events, runtime {tc(total, args.fps)} ({total / args.fps:.2f} s at {args.fps} fps)")


if __name__ == "__main__":
    main()
